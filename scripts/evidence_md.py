#!/usr/bin/env python3
"""Generate EVIDENCE.md from PUBLISH.tsv (published numbers) and docs/evidence-gates.tsv (gate commands).
   python3 scripts/evidence_md.py           write EVIDENCE.md
   python3 scripts/evidence_md.py --check   exit 1 if EVIDENCE.md differs from what the sources generate"""
import csv, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def build() -> str:
    pub = list(csv.DictReader((ROOT / "PUBLISH.tsv").open(encoding="utf-8"), delimiter="\t"))
    gates = list(csv.DictReader((ROOT / "docs" / "evidence-gates.tsv").open(encoding="utf-8"), delimiter="\t"))
    out = ["# Evidence", "", "Generated by `python3 scripts/evidence_md.py`; `--check` fails on drift. Each row is a claim, the command that proves it, and the expected output.", "",
           f"## Gates ({len(gates)})", "", "| Claim | Command | Expected last line |", "|---|---|---|"]
    for g in gates:
        out.append(f"| {g['claim']} | `{g['command']}` | `{g['expected']}` |")
    out += ["", f"## Published numbers ({len(pub)})", "", "| Claim | Command | Expected output |", "|---|---|---|"]
    for r in pub:
        label = (r.get("label") or r["id"]).replace("|", "/")
        out.append(f"| {label} | `{r['command']}` | `{r['expected_output']}` |")
    out += ["", "## Receipt provenance", "",
            "The current train receipts predate the derived producer list: they carry a `code_sha` of the six legacy producer files and no `producer_files` manifest, and `ftlab report --check` verifies them against that legacy list. The next retrain (owner button, about 11 minutes) records `producer_files` in each train receipt and regenerates them against the full derived set, which covers `config.py` and `registry.py`."]
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    text = build()
    target = ROOT / "EVIDENCE.md"
    if "--check" in sys.argv:
        ok = target.exists() and target.read_text(encoding="utf-8") == text
        print("evidence: GREEN" if ok else "evidence: RED (EVIDENCE.md drifted; run scripts/evidence_md.py)")
        sys.exit(0 if ok else 1)
    target.write_text(text, encoding="utf-8")
    print("wrote EVIDENCE.md")
